/** Returns { key, sa, eg } when the message is one of the conversation-layer topics, else null. */
export function extraTopic(t, toks, c = {}) {
  const hasQuote = !!c.hasQuote
  const wordCount = toks.length
  const svc = !!c.spec || !!c.qty
  // sales / trust / lead-capture layer (answers carry no prices: facts only from what the business promises)
  if (P.callback.test(t) && wordCount <= 9) return { key: 'callback', escalate: 'human', ...TV.callback }
  if (P.refund.test(t)) return { key: 'refund', escalate: 'refund', ...TV.refund }
  if (P.visit_fee.test(t)) return { key: 'visit_fee', ...TV.visit_fee }
  if (P.package_vs_wash.test(t)) return { key: 'package_vs_wash', ...TV.package_vs_wash }
  if (P.method.test(t) && wordCount <= 8) return { key: 'method', ...TV.method }
  if (P.own_tech.test(t)) return { key: 'own_tech', ...TV.own_tech }
  if (P.papers.test(t)) return { key: 'papers', escalate: 'human', ...TV.papers }
  if (P.trust_fear.test(t)) return { key: 'trust_fear', ...TV.trust_fear }
  if (P.show_works.test(t) && wordCount <= 8) return { key: 'show_works', escalate: 'human', ...TV.show_works }
  if (P.track_tech.test(t) && !c.hasOrders) return { key: 'track_tech', ...TV.track_tech }
  if (P.join_how.test(t)) return { key: 'join_how', ...TV.join_how }
  if (P.change_slot.test(t) && !c.hasDraft && !c.hasOrders) return { key: 'change_slot', escalate: 'human', ...TV.change_slot }
  if (P.think_later.test(t) && !hasQuote) return { key: 'think_later', ...TV.think_later }
  if (P.consult.test(t) && wordCount <= 3) return { key: 'consult', ...TV.consult }
  if (P.contact_info.test(t) && wordCount <= 8) return { key: 'contact_info', ...TV.contact_info }
  if (P.haggle_soft.test(t) && !hasQuote && !c.hasDraft) return { key: 'haggle_soft', ...TV.haggle_soft }
  if (P.tech_nationality.test(t)) return { key: 'tech_nationality', ...TV.tech_nationality }
  if (P.annual_pkg.test(t) && !P.business.test(t)) return { key: 'annual_pkg', escalate: 'human', ...TV.annual_pkg }
  if (P.part_change.test(t) && !c.hasDraft) return { key: 'part_change', ...TV.part_change }
  if (P.project.test(t) && !c.spec) return { key: 'project', escalate: 'human', ...TV.project }
  if (P.business.test(t) && ((!c.spec && !c.qty) || /(عماره|عمارتي|مطعم|فندق|مدرسه|مستشفي|عقد|عرض سعر)/.test(t))) return { key: 'business', escalate: 'human', ...TV.business }
  if (P.compare.test(t)) return { key: 'compare', ...TV.compare }
  if (P.why_us.test(t)) return { key: 'why_us', ...TV.why_us }
  if (P.experience.test(t) && wordCount <= 8 && !P.device_age.test(t)) return { key: 'experience', ...TV.experience }
  if (P.triage.test(t)) return { key: 'triage', ...TV.triage }
  if (P.howru.test(t) && wordCount <= 5 && !svc) return { key: 'howru', ...TV.howru }
  if (P.tired.test(t) && wordCount <= 5 && !svc) return { key: 'tired', ...TV.tired }
  if (P.praise.test(t) && wordCount <= 5 && !svc) return { key: 'praise', ...TV.praise }
  if (P.hours.test(t) && wordCount <= 9) return { key: 'hours', ...TV.hours }
  if (P.budget.test(t) && !hasQuote) return { key: 'budget', ...TV.budget }
  if (P.objection.test(t) && (hasQuote || c.hasDraft)) return { key: 'objection', ...TV.objection }
  if (P.device_age.test(t) && !svc && c.hasDraft && /(مكيف|سبليت|شباك|يبرد|صوت)/.test(t + ' ' + (c.problem || '')) ) return { key: 'device_age', ...TV.device_age }
  return null
}

