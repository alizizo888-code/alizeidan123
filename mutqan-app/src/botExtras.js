/** Returns { key, sa, eg } when the message is one of the conversation-layer topics, else null. */
export function extraTopic(t, toks, c = {}) {
  const hasQuote = !!c.hasQuote
  const wordCount = toks.length
  const svc = !!c.spec || !!c.qty
  if (P.compare.test(t)) return { key: 'compare', ...TV.compare }
  if (P.why_us.test(t)) return { key: 'why_us', ...TV.why_us }
  if (P.experience.test(t) && wordCount <= 8 && !P.device_age.test(t)) return { key: 'experience', ...TV.experience }
  if (P.triage.test(t)) return { key: 'triage', ...TV.triage }
  if (P.howru.test(t) && wordCount <= 5 && !svc) return { key: 'howru', ...TV.howru }
  if (P.tired.test(t) && wordCount <= 5 && !svc) return { key: 'tired', ...TV.tired }
  if (P.praise.test(t) && wordCount <= 5 && !svc) return { key: 'praise', ...TV.praise }
  if (P.hours.test(t) && wordCount <= 9) return { key: 'hours', ...TV.hours }
  if (P.budget.test(t) && !hasQuote) return { key: 'budget', ...TV.budget }
  if (P.objection.test(t) && (hasQuote || c.hasDraft)) return { key: 'objection', ...TV.objection }
  if (P.device_age.test(t) && !svc && c.hasDraft && /(مكيف|سبليت|شباك|يبرد|صوت)/.test(t + ' ' + (c.problem || '')) ) return { key: 'device_age', ...TV.device_age }
  return null
}

