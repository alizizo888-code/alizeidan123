// «لائحة العمل والجزاءات» — attached to every technician contract (owner order 2026-11-22). The amounts come from the
// owner's own rules (tech_pay.rules, lib/penalties.js) so the paper and the automatic suggestions always say the same.
import { ruleVal } from './penalties'

export function regulations(rules, brand = 'الشركة') {
  const v = (id) => ruleVal(rules, id)
  return `ملحق العقد: لائحة العمل والجزاءات — ${brand}

أولًا: الالتزامات العامة
1. كل الشغل يتم من خلال التطبيق فقط: الطلب، السعر، الفاتورة، والدفع. أي اتفاق جانبي مع عميل جاء عن طريق ${brand} ممنوع.
2. الالتزام بالأسعار المعتمدة في التطبيق، وأي زيادة (قطع غيار / شغل إضافي) لازم تتسجل في الطلب ويوافق عليها العميل قبل التنفيذ.
3. الوصول في الموعد، وتحديث حالة الطلب أول بأول (في الطريق / وصلت / بدأت / انتهيت)، وتشغيل الموقع طول ما أنت متصل.
4. حسن التعامل والمظهر، واحترام بيت العميل وخصوصيته، وعدم التدخين أو رفع الصوت عنده.
5. تصوير الحالة قبل وبعد الشغل ورفع الصور على الطلب، وتسجيل أي ملاحظة على الجهاز.
6. لا يجوز تحصيل أي مبلغ نقدي خارج الفاتورة، ويُفضَّل تحويل العميل على حسابات الشركة: نسبتك في التحويل أعلى من الكاش.

ثانيًا: الحساب والمستحقات
7. نظام الحساب المعتمد لك (نسبة أو رصيد مسبق) يظهر في صفحتك، ومعاه كشف حساب بكل حركة.
8. طلب تحويل المستحقات من زر «اطلب تحويل مستحقاتي»، ويتم التحويل خلال يوم عمل على الحساب المسجل باسمك.
9. في نظام الرصيد المسبق: لو الرصيد نزل عن الحد الأدنى يتوقف استلام الطلبات لحد الشحن.

ثالثًا: الجزاءات (كل خصم يُعرض على الإدارة للاعتماد قبل تطبيقه، ومن حقك الاعتراض خلال 48 ساعة)
10. الاعتذار عن طلب بعد إسناده لك بدون ظرف مقبول: خصم ${v('decline')} ر.س.
11. زيارة فاشلة بسبب يخصك (نقص عدة، خارج تخصصك…): خصم ${v('abort')} ر.س.
12. التأخير عن موعد العميل أكثر من ساعة بدون إبلاغ: خصم ${v('late')} ر.س.
13. تقييم سيء (1 أو 2 من 5) بعد مراجعة الإدارة: خصم ${v('badRating')} ر.س، وتكراره يقلل أولويتك في التوزيع.
14. الشغل المرتجع: لو العطل رجع خلال فترة الضمان بسبب شغلك، تنفّذ الإصلاح مجانًا، ويُخصم ${v('returnJob')}% من قيمة الشغل الأصلي لو تكرر أو كان الخطأ واضحًا. لو المرتجع مش بسببك (عيب قطعة / سوء استخدام) يتحسب لك كطلب عادي.
15. التعامل مع عميل خارج التطبيق: خصم ${v('offApp')} ر.س أول مرة، والتكرار = إنهاء التعامل نهائيًا.
16. أي مشكلة أو ضرر أو شكوى عن شغل تم خارج التطبيق يتحملها الفني وحده بالكامل، و${brand} غير مسؤولة عنها.

رابعًا: الخصوصية والملكية
17. بيانات العملاء (الأسماء، الأرقام، العناوين) ملك ${brand}، ولا يجوز حفظها أو نقلها أو استخدامها لأي غرض خارج التطبيق، حتى بعد انتهاء التعاقد.
18. اسم وشعار ${brand} وصور الأعمال والمحتوى ملك للشركة، ولا يجوز استخدامها في حسابات أو إعلانات شخصية بدون إذن مكتوب.
19. الحساب على التطبيق شخصي، ولا يجوز تسليمه لفني آخر.

خامسًا: أحكام عامة
20. التعامل بيننا قائم على الأمانة والثقة والود، والإدارة تراجع أي خلاف بالحوار قبل أي جزاء.
21. يحق للشركة تعديل هذه اللائحة مع إشعار الفني في التطبيق، والاستمرار في العمل بعد الإشعار يعني الموافقة.`
}
