    private static $cache = null;

    /** The full library: one entry per situation × archetype × context. */
    public static function all() {
        if (self::$cache !== null) { return self::$cache; }
        $out = [];
        $sit = self::situations(); $arc = self::archetypes(); $ctx = self::contexts();
        foreach ($sit as $sid => $s) {
            foreach ($arc as $aid => $a) {
                foreach ($ctx as $cid => $c) {
                    $give = round(min(1.5, (float) $s[5] * (float) $a['give'] * (float) $c['give']), 2);
                    $out[$sid . '.' . $aid . '.' . $cid] = [
                        'id' => $sid . '.' . $aid . '.' . $cid,
                        'situation' => $sid, 'archetype' => $aid, 'context' => $cid,
                        'title' => $s[0] . ' — ' . $a['label'] . ' — ' . $c['label'],
                        'stage' => $s[1],
                        'tactic' => $s[3],
                        'persona' => $a['tone'],
                        'timing' => $s[1] === 'nego' || $s[1] === 'time' ? $c['adj'] : '',
                        'action' => $s[4],
                        'give' => $give,
                        'say' => $s[6],
                    ];
                }
            }
        }
        return self::$cache = $out;
    }

    public static function count() { return count(self::all()); }

    public static function get($id) { $a = self::all(); return $a[$id] ?? null; }

    /* ------------------------------------------------------------------ detection */

    public static function norm($s) {
        $s = mb_strtolower((string) $s);
        $s = strtr($s, ['أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ة' => 'ه', 'ى' => 'ي', 'ؤ' => 'و', 'ئ' => 'ي', 'ـ' => '']);
        $s = preg_replace('/[\x{064B}-\x{0652}]/u', '', $s);
        $s = strtr($s, ['٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4', '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9']);
        return trim(preg_replace('/\s+/u', ' ', $s));
    }

    /** First money-looking number in the message (2–5 digits), or null. */
    public static function money_in($text) {
        if (preg_match('/(?<!\d)(\d{2,5})(?!\d)/u', self::norm($text), $m)) { return (int) $m[1]; }
        return null;
    }

    /**
     * The situation the last customer message puts us in.
     *
     * $state: ['quoted' => bool (a price was already given), 'asks' => int (discount requests so far),
     *          'floor' => ?int, 'agreed' => bool, 'city' => ?string]
     */
    public static function detect($text, $state = []) {
        $n = self::norm($text);
        if ($n === '') { return 'greet_browse'; }
        $quoted = !empty($state['quoted']);
        $asks = (int) ($state['asks'] ?? 0);
        $k = self::money_in($text);

        // A number after a price was given is a counter offer — the strongest signal there is.
        if ($quoted && $k !== null && $k >= 20 && !preg_match('/(مكيف|وحده|وحدات|جهاز|ساعه|الساعه|يوم)/u', $n)) {
            $floor = isset($state['floor']) ? (int) $state['floor'] : null;
            return ($floor !== null && $k >= $floor) ? 'counter_ok' : 'counter_low';
        }
        $scores = [];
        foreach (self::situations() as $sid => $s) {
            $sc = 0;
            foreach ($s[2] as $w) {
                $w = self::norm($w);
                if ($w !== '' && mb_strpos($n, $w) !== false) { $sc += 1 + mb_strlen($w) / 10; }
            }
            if ($sc > 0) { $scores[$sid] = $sc; }
        }
        if (!$scores) { return $quoted ? 'think_later' : 'vague_need'; }
        // A discount asked for again is a different moment from the first time.
        if (isset($scores['discount_first']) && $asks >= 1) { $scores['discount_repeat'] = ($scores['discount_repeat'] ?? 0) + $scores['discount_first'] + 0.5; unset($scores['discount_first']); }
        // Once a price is on the table, «كم السعر؟ غالي» is a complaint about it, not a new price question.
        if ($quoted && isset($scores['price_first'])) {
            $sits = self::situations();
            foreach ($scores as $sid => $v) { if ($sid !== 'price_first' && $sits[$sid][1] === 'nego') { unset($scores['price_first']); break; } }
        }
        // «تمام» before any price is a greeting, not an agreement.
        if (isset($scores['accept_price']) && !$quoted) { unset($scores['accept_price']); }
        if (!empty($state['agreed']) && isset($scores['accept_price'])) { $scores['upsell_warranty'] = ($scores['upsell_warranty'] ?? 0) + 0.2; }
        if (!$scores) { return 'vague_need'; }
        arsort($scores);
        return (string) array_key_first($scores);
    }

