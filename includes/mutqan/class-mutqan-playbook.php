    public static function phrase($scenario, $dialect = 'sa', $vars = [], $seed = 0) {
        $list = (array) ($scenario['say'] ?? []);
        if (!$list) { return ''; }
        $t = $list[abs((int) $seed) % count($list)];
        if ($dialect === 'eg') { $t = strtr($t, self::$EG); }
        $rep = ['{n}' => isset($vars['n']) && $vars['n'] !== '' ? ' ' . $vars['n'] : ''];
        foreach (['p', 'o', 'k', 's'] as $v) { $rep['{' . $v . '}'] = isset($vars[$v]) && $vars[$v] !== '' && $vars[$v] !== null ? (string) $vars[$v] : '—'; }
        return strtr($t, $rep);
    }

    /** Search the library (owner screen / agent tool). */
    public static function search($q = '', $limit = 30, $filters = []) {
        $q = self::norm($q); $out = [];
        foreach (self::all() as $id => $s) {
            foreach (['situation', 'archetype', 'context', 'stage'] as $f) { if (!empty($filters[$f]) && $s[$f] !== $filters[$f]) { continue 2; } }
            if ($q !== '' && mb_strpos(self::norm($s['title'] . ' ' . $s['tactic'] . ' ' . implode(' ', $s['say'])), $q) === false) { continue; }
            $out[] = ['id' => $id, 'title' => $s['title'], 'stage' => $s['stage'], 'action' => $s['action'], 'give' => $s['give'], 'tactic' => $s['tactic'], 'persona' => $s['persona'], 'timing' => $s['timing'], 'sample' => self::phrase($s, 'sa', ['p' => '٢٠٠', 'o' => '١٨٠', 'k' => '١٥٠', 's' => 'بكرة ١٠ ص'])];
            if (count($out) >= max(1, min(200, (int) $limit))) { break; }
        }
        return $out;
    }

